import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'rolldown';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const nobleDir = dirname(fileURLToPath(import.meta.resolve('@noble/hashes/sha2.js')));
const pkg = JSON.parse(await readFile(join(nobleDir, 'package.json'), 'utf8'));
if (pkg.version !== '2.4.0') throw new Error('sample hash generator requires exactly @noble/hashes 2.4.0');
const license = (await readFile(join(nobleDir, 'LICENSE'), 'utf8')).trim();
const bundled = await build({
  input: join(root, 'scripts/sample-hash-entry.mjs'), cwd: root, platform: 'browser',
  write: false, output: { format: 'esm' }, logLevel: 'silent',
});
if (bundled.output.length !== 1 || bundled.output[0].type !== 'chunk' || bundled.output[0].imports.length) throw new Error('sample hash must be one self-contained module');
const generated = `// @ts-nocheck\n// Generated by scripts/vendor-sample-hash.mjs from @noble/hashes 2.4.0. Do not edit.\n/*\n${license}\n*/\n${bundled.output[0].code}`;
const target = join(root, 'runtime/engine/sample-hash.js');
const mode = process.argv[2];
if (mode === '--write') { await writeFile(target, generated); console.log('sample-hash.js written'); }
else if (mode === '--check') {
  if (await readFile(target, 'utf8').catch(() => '') !== generated) throw new Error('sample-hash.js differs; run node scripts/vendor-sample-hash.mjs --write');
  console.log('sample-hash.js up to date');
} else throw new Error('usage: node scripts/vendor-sample-hash.mjs --write|--check');
