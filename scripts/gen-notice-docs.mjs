// docs/notices.md: every notice code and every error code with its category, generated from the registries in src/notices.ts and
// src/errors.ts so the page cannot drift from what the commands can emit. `node scripts/gen-notice-docs.mjs --write` regenerates it;
// `--check` (tests/notice-docs.test.ts) fails when stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { NOTICE_CODES, NOTICE_REGISTRY } from '../src/notices.ts';
import { ERROR_CATEGORIES, ERROR_CODES } from '../src/errors.ts';

const target = resolve(import.meta.dirname, '..', 'docs/notices.md');
const cell = text => text.replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();

const lines = [
  '# Notices and errors',
  '',
  '<!-- Generated by scripts/gen-notice-docs.mjs from src/notices.ts and src/errors.ts; do not edit. -->',
  '',
  '## Notices',
  '',
  'A notice is something a command did on your behalf that the input did not say: a value changed, a result narrowed, a request that had nothing to act on. It never fails a command. Commands that can produce one add a `notices` array to their JSON (and nothing when there is nothing to say); match on `code`, not on the message.',
  '',
  '```json',
  '{ "code": "N_SCALE_SNAP", "severity": "warn", "message": "...", "pointer": "/layers/0/source/pitch", "requested": 466, "applied": "A#4", "hint": "..." }',
  '```',
  '',
  '`severity` is `warn` when the caller may be acting on a false belief and `info` when the output is merely narrower than it looks. `pointer`, `requested` and `applied` are present when they apply.',
  '',
  '| Code | Severity | Meaning | What to do |',
  '| --- | --- | --- | --- |',
  ...NOTICE_CODES.map(code => `| \`${code}\` | ${NOTICE_REGISTRY[code].severity} | ${cell(NOTICE_REGISTRY[code].summary)} | ${cell(NOTICE_REGISTRY[code].hint)} |`),
  '',
  '## Errors',
  '',
  'A failure is an error on stderr, `{ "error": { "code", "category", "retryable", "message", ... } }`, with exit code 1 (2 for a usage error caught while parsing options). `pointer` names the field at fault, `hint` says what to do, and `received` echoes the rejected value (cut to 80 characters). `category` says who has to act: change your input, repair the environment, accept the outcome, retry, or report a bug.',
  '',
  '| Code | Category | Retryable |',
  '| --- | --- | --- |',
  ...ERROR_CODES.map(code => `| \`${code}\` | ${ERROR_CATEGORIES[code]} | ${ERROR_CATEGORIES[code] === 'transient' ? 'yes' : 'no'} |`),
  '',
];
const generated = lines.join('\n');

if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== generated) { console.error('docs/notices.md is stale; run node scripts/gen-notice-docs.mjs --write'); process.exit(1); }
} else if (process.argv.includes('--write')) {
  writeFileSync(target, generated);
  console.log(`docs/notices.md written (${NOTICE_CODES.length} notices, ${ERROR_CODES.length} errors)`);
} else process.stdout.write(generated);
