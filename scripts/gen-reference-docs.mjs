// docs/reference.md: the archetypes, library collections, instruments and craft rules the plugin ships, generated from the files themselves so the
// page cannot drift from them. `node scripts/gen-reference-docs.mjs --write` regenerates it; `--check` (tests/reference-docs.test.ts) fails when stale.
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join, relative, resolve } from 'node:path';
import { loadArchetypes } from '../src/archetypes.ts';
import { libraryInstruments } from '../src/music.ts';

const root = resolve(import.meta.dirname, '..');
const target = join(root, 'docs/reference.md');
const cell = text => String(text ?? '').replace(/\|/g, '\\|').replace(/\s+/g, ' ').trim();
const json = path => JSON.parse(readFileSync(path, 'utf8'));

/** Every patch file under a collection folder (not its project.json or kit.json), sorted by path. */
function patchFiles(dir) {
  const out = [];
  const walk = d => {
    for (const e of readdirSync(d, { withFileTypes: true }).sort((a, b) => (a.name < b.name ? -1 : 1))) {
      const p = join(d, e.name);
      if (e.isDirectory()) walk(p);
      else if (e.name.endsWith('.json') && e.name !== 'project.json' && e.name !== 'kit.json') out.push(p);
    }
  };
  walk(dir);
  return out;
}

const archetypes = loadArchetypes().sort((a, b) => (a.name < b.name ? -1 : 1));
const sounds = join(root, 'library/sounds');
const collections = readdirSync(sounds, { withFileTypes: true }).filter(e => e.isDirectory()).map(e => e.name).sort();
const rules = file => json(join(root, 'craft', file)).rules;

const lines = [
  '# Reference: what ships',
  '',
  '<!-- Generated by scripts/gen-reference-docs.mjs from library/ and craft/; do not edit. -->',
  '',
  'Everything here is read from the shipped files, so it is current. `beeps archetypes`, `beeps instruments` and `beeps capabilities` print the same data as JSON.',
  '',
  '## Archetypes',
  '',
  '`beeps generate <archetype>` samples one. The recipe is what it is built from; the family sets its loudness offset and tail ceiling.',
  '',
  '| Archetype | Family | Recipe | Ranges |',
  '| --- | --- | --- | --- |',
  ...archetypes.map(a => `| \`${a.name}\` | ${a.family} | ${cell(a.recipe)} | ${Object.keys(a.ranges).length} |`),
  '',
  '## Sound collections',
  '',
  'Authored patches under `library/sounds/`. Copy one into a project with `beeps sync` or read it as an example.',
  '',
  ...collections.flatMap(c => {
    const files = patchFiles(join(sounds, c));
    return [
      `### ${c} (${files.length})`,
      '',
      '| Patch | Family | Intent |',
      '| --- | --- | --- |',
      ...files.map(f => {
        const p = json(f);
        const rel = relative(join(sounds, c), f).split('\\').join('/');
        return `| \`${rel}\` | ${cell(p.family)} | ${cell(p.meta?.description ?? '')} |`;
      }),
      '',
    ];
  }),
  '## Instruments',
  '',
  'Patches songs play by name (`beeps instruments`). Root is the note the layers sound at as built; a written note far from it is retuned (lint `song-written-pitch`).',
  '',
  '| Instrument | Root | Plays | Description |',
  '| --- | --- | --- | --- |',
  ...libraryInstruments().map(i => `| \`${i.name}\` | ${i.root ?? 'unpitched'} | ${cell(i.plays)} | ${cell(i.description ?? '')} |`),
  '',
  '## Craft rules',
  '',
  'Every rule cites its sources in `craft/rules.json` and `craft/music-rules.json`. `auto` rules are checked by `beeps lint` and `beeps song lint`; `judgement` rules are listed for the author to weigh.',
  '',
  ...[['Sound rules', 'rules.json'], ['Music rules', 'music-rules.json']].flatMap(([title, file]) => [
    `### ${title}`,
    '',
    '| Rule | Severity | Check | Applies to | Statement |',
    '| --- | --- | --- | --- | --- |',
    ...rules(file).map(r => `| \`${r.id}\` | ${r.severity} | ${r.check} | ${r.appliesTo} | ${cell(r.statement)} |`),
    '',
  ]),
];
const generated = lines.join('\n');

if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== generated) { console.error('docs/reference.md is stale; run node scripts/gen-reference-docs.mjs --write'); process.exit(1); }
} else if (process.argv.includes('--write')) {
  writeFileSync(target, generated);
  console.log(`docs/reference.md written (${archetypes.length} archetypes, ${collections.length} collections)`);
} else process.stdout.write(generated);
