// docs/cli.md: every runnable beeps command with its one-line description, generated from the commander tree so it cannot
// drift from the CLI. `node scripts/gen-cli-docs.mjs --write` regenerates it; `--check` (tests/cli-docs.test.ts) fails when stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { buildProgram } from '../src/cli.ts';
import { leafCommands } from '../src/commands/inventory.ts';

const target = resolve(import.meta.dirname, '..', 'docs/cli.md');
const program = buildProgram({ emit() {}, projectDir: () => process.cwd() });
const commands = leafCommands(program);

const cell = text => text.replace(/\|/g, '\|').replace(/\s+/g, ' ').trim();
const groupOf = name => (name.includes(' ') ? name.split(' ')[0] : null);
const groups = new Map();
for (const c of commands) {
  const key = groupOf(c.name) ?? 'core';
  if (!groups.has(key)) groups.set(key, []);
  groups.get(key).push(c);
}

const lines = [
  '# beeps commands',
  '',
  '<!-- Generated by scripts/gen-cli-docs.mjs from the CLI itself; do not edit. -->',
  '',
  `${commands.length} commands. Every one prints JSON on stdout; \`beeps <command> --help\` lists its options, and the skills explain when to use each.`,
  '',
];
for (const [key, list] of groups) {
  lines.push(`## ${key === 'core' ? 'Top-level commands' : `\`${key}\``}`, '', '| Command | What it does |', '| --- | --- |');
  for (const c of list) lines.push(`| \`beeps ${c.name}\` | ${cell(c.description)} |`);
  lines.push('');
}
const generated = lines.join('\n');

if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== generated) { console.error('docs/cli.md is stale; run node scripts/gen-cli-docs.mjs --write'); process.exit(1); }
} else if (process.argv.includes('--write')) {
  writeFileSync(target, generated);
  console.log(`docs/cli.md written (${commands.length} commands)`);
} else process.stdout.write(generated);
