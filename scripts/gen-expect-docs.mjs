// docs/expectations.md: the kinds of check an `xExpect` entry can make, generated from EXPECT_REGISTRY in src/expect.ts so the page cannot drift
// from what the evaluator does. `node scripts/gen-expect-docs.mjs --write` regenerates it; `--check` (tests/expect-docs.test.ts) fails when stale.
import { readFileSync, writeFileSync } from 'node:fs';
import { resolve } from 'node:path';
import { EXPECT_REGISTRY } from '../src/expect.ts';
import { EXPECT_KINDS } from '../src/schema/patch.ts';

const target = resolve(import.meta.dirname, '..', 'docs/expectations.md');
const cell = text => text.replace(/\|/g, '\|').replace(/\s+/g, ' ').trim();

const lines = [
  '# Patch expectations',
  '',
  '<!-- Generated by scripts/gen-expect-docs.mjs from src/expect.ts; do not edit. -->',
  '',
  'A patch can carry an `xExpect` block: checkable statements about how the sound should measure. Declaring one never changes a render (it is not part of a render key, and a runtime cue leaves it out). `beeps lint` and `beeps kit check` report an `expectations` verdict for each patch that has one and exit 1 when it fails; `beeps build` refuses to ship a recipe whose expectations fail (`E_VERIFY`) when it renders that asset.',
  '',
  '```json',
  '"xExpect": [',
  '  { "check": "duration", "max": 0.35 },',
  '  { "check": "centroid", "min": 1800, "max": 4200 },',
  '  { "check": "pitch", "note": "A5", "toleranceCents": 50 },',
  '  { "check": "pitch-direction", "is": "rising" }',
  ']',
  '```',
  '',
  'Every entry is a strict object keyed by `check`; an unknown kind or field is an `E_SCHEMA` error naming the pointer, and `min` above `max` is an error. Units are fixed per kind and echoed in each verdict. The check runs on every variant the patch declares: a failure names the first variant that fails, and a check that passes variant 0 but fails variant 3 is reported, never averaged.',
  '',
  '## Kinds',
  '',
  '| Check | Reads | Fields | Unit | Meaning |',
  '| --- | --- | --- | --- | --- |',
  ...EXPECT_KINDS.map(k => `| \`${k}\` | \`${cell(EXPECT_REGISTRY[k].reads)}\` | ${cell(EXPECT_REGISTRY[k].fields)} | ${EXPECT_REGISTRY[k].unit} | ${cell(EXPECT_REGISTRY[k].summary)} |`),
  '',
  '## The verdict',
  '',
  '```json',
  '"expectations": {',
  '  "passed": false,',
  '  "checks": [',
  '    { "kind": "tail", "outcome": "fail", "pointer": "/xExpect/2", "unit": "s", "expected": { "max": 0.12 }, "actual": 0.31,',
  '      "hint": "shorten the release or lower the reverb or delay send; the tail is measured to 60 dB below the peak" }',
  '  ]',
  '}',
  '```',
  '',
  'An outcome is `pass`, `fail` or `unmeasurable`. Unmeasurable counts as a failure, with a `reason`: a contract that cannot be checked is not met (pitch on a noise burst, for example). `pointer` names the entry to edit and `hint` says which parameters move the measurement. Loudness is not a check: the renderer trims every sound to the project target, so asserting it would test the trim; `peak-limited` is the exception that documents a spiky sound sitting below target by design.',
  '',
  'Expectations are not craft rules. Lint rules are general, each cites a source, and a failing rule is an `error` or `warning`; an expectation is this sound\'s own brief, has no citation, and appears only under `expectations`.',
  '',
];
const generated = lines.join('\n');

if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== generated) { console.error('docs/expectations.md is stale; run node scripts/gen-expect-docs.mjs --write'); process.exit(1); }
} else if (process.argv.includes('--write')) {
  writeFileSync(target, generated);
  console.log(`docs/expectations.md written (${EXPECT_KINDS.length} kinds)`);
} else process.stdout.write(generated);
