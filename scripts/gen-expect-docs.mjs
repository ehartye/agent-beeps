const generated = lines.join('\n');

if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== generated) { console.error('docs/expectations.md is stale; run node scripts/gen-expect-docs.mjs --write'); process.exit(1); }
} else if (process.argv.includes('--write')) {
  writeFileSync(target, generated);
  console.log(`docs/expectations.md written (${EXPECT_KINDS.length} kinds)`);
} else process.stdout.write(generated);
