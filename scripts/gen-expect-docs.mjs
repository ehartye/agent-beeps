  '',
  '## Writing the numbers: pin a sound as it is',
  '',
  '`beeps lint <patch> --derive-expect` adds, per patch, `derived.xExpect`: a block the sound passes as it measures now, with room around each number. Edit it, then save it into the patch. It turns a good sound into regression protection ("this chime must stay this chime") and gives an agent numbers to start from instead of guesses.',
