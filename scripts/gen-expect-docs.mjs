  ']',
  '```',
  '',
  'Every entry is a strict object keyed by `check`; an unknown kind or field is an `E_SCHEMA` error naming the pointer, and `min` above `max` is an error. Units are fixed per kind and echoed in each verdict. The check runs on every variant the patch declares: a failure names the first variant that fails, and a check that passes variant 0 but fails variant 3 is reported, never averaged.',
