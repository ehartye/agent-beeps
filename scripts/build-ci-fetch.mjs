// Generate the portable Node20+ CI artifact from the shared delivered-asset validator.
import { readFile, writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { build } from 'rolldown';
const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const pkg = JSON.parse(await readFile(join(root, 'node_modules/rolldown/package.json'), 'utf8'));
if (pkg.version !== '1.2.11') throw new Error('CI fetch generator requires rolldown 1.2.11');
const result = await build({input: join(root, 'scripts/ci-fetch-entry.mjs'), cwd: root, platform: 'node', write: false,
  output: {format: 'esm', codeSplitting: false}, logLevel: 'silent'});
if (result.output.length !== 1 || result.output[0].type !== 'chunk' || result.output[0].imports.some(s => !s.startsWith('node:'))) throw new Error('CI fetch must be one built-ins-only script');
const code = result.output[0].code;
if ((code.match(/__BEEPS_DEFAULTS__/g) ?? []).length !== 1) throw new Error('CI fetch defaults placeholder lost');
const generated = code.replace('#!/usr/bin/env node\n', '#!/usr/bin/env node\n// Generated by scripts/build-ci-fetch.mjs. Do not edit.\n').replace('__BEEPS_DEFAULTS__', '/*beeps:defaults*/ {}');
const target = join(root, 'runtime/ci/fetch.mjs');
if (process.argv[2] === '--write') { await writeFile(target, generated); console.log('fetch.mjs written'); }
else if (process.argv[2] === '--check') {
  if (await readFile(target, 'utf8') !== generated) throw new Error('fetch.mjs differs; run node scripts/build-ci-fetch.mjs --write');
  console.log('fetch.mjs up to date');
} else throw new Error('usage: node scripts/build-ci-fetch.mjs --write|--check');
